class Personagem{
   cuctor(mana, vida, forca){
    mana = mana,
    this.forca = forca,
    this.vida = vida
   }
}
class Guerreiro extends Personagem{
    constructor(mana, vida, forca){
        super(mana, vida, forca)
    mana = mana,
    forca = forca,
    vida = vida
    }
}
